"""Benchmark every model family and rewrite docs/benchmarks.md.

Usage::

    python scripts/benchmark.py            # or: make benchmark
    python scripts/benchmark.py --data path/to/train.csv --out docs/benchmarks.md

For each task and model the script reports two things:

* the score on the notebook's held-out split (80/20, seed 42), which is
  directly comparable with the published notebook numbers, and
* 5-fold cross-validation on the full dataset (mean and standard deviation),
  which is far less sensitive to which 292 houses happen to be in one split.
"""

from __future__ import annotations

import argparse
import platform
import warnings
from collections.abc import Iterator
from dataclasses import dataclass
from datetime import date
from pathlib import Path

import numpy as np
import pandas as pd
import sklearn
from sklearn.model_selection import KFold, StratifiedKFold, cross_val_score

from amesml import ClassificationMetrics, RegressionMetrics, TrainConfig, __version__, load_ames
from amesml import train as train_model
from amesml.models import build_pipeline, plan_features, price_labels, resolve_threshold

MODELS = ("linear", "ridge", "lasso", "gbm")


@dataclass(frozen=True)
class Row:
    label: str
    config: TrainConfig
    test: RegressionMetrics | ClassificationMetrics
    cv_mean: float
    cv_std: float


def variants(task: str) -> Iterator[tuple[str, TrainConfig]]:
    for model in MODELS:
        yield model, TrainConfig(task=task, model=model)
    yield "gbm + engineered features", TrainConfig(task=task, model="gbm", engineer_features=True)


def cross_validate(frame: pd.DataFrame, config: TrainConfig) -> tuple[float, float]:
    plan = plan_features(frame, config)
    inputs = frame[list(plan.input_columns)]
    if config.task == "regression":
        target, scoring = frame[config.target], "neg_root_mean_squared_error"
        folds: KFold | StratifiedKFold = KFold(5, shuffle=True, random_state=config.random_state)
    else:
        prices = frame[config.target]
        target = price_labels(prices, resolve_threshold(prices, config.threshold))
        scoring = "roc_auc"
        folds = StratifiedKFold(5, shuffle=True, random_state=config.random_state)
    scores = cross_val_score(
        build_pipeline(plan, config), inputs, target, cv=folds, scoring=scoring
    )
    if config.task == "regression":
        scores = -scores
    return float(np.mean(scores)), float(np.std(scores))


def run(frame: pd.DataFrame) -> dict[str, list[Row]]:
    results: dict[str, list[Row]] = {}
    for task in ("regression", "classification"):
        rows = []
        for label, config in variants(task):
            test = train_model(frame, config).metrics
            mean, std = cross_validate(frame, config)
            rows.append(Row(label, config, test, mean, std))
            print(f"{task:>14}  {label:<28} done")
        results[task] = rows
    return results


def alpha_note(config: TrainConfig) -> str:
    alpha = config.resolved_alpha
    return "-" if alpha is None else f"{alpha:g}"


def render(results: dict[str, list[Row]]) -> str:
    lines = [
        "# Benchmarks",
        "",
        "<!-- Generated by scripts/benchmark.py - edit the script, not this file. -->",
        "",
        "Every model family on the Kaggle Ames training data (1,460 sales), with each",
        "model's default configuration. Two views of each model:",
        "",
        "- **Held-out test**: the notebook's split (80/20, seed 42; 292 test houses).",
        "  The `linear` rows reproduce the published notebook results exactly.",
        "- **5-fold CV**: cross-validation over all 1,460 houses, mean ± standard",
        "  deviation. Less dependent on which houses land in one split, so this is",
        "  the column to compare models by.",
        "",
        "## Regression: predicting the sale price",
        "",
        "| Model | alpha | Test MAE | Test RMSE | Test R² | Test MAPE | 5-fold CV RMSE |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for row in results["regression"]:
        m = row.test
        assert isinstance(m, RegressionMetrics)
        lines.append(
            f"| {row.label} | {alpha_note(row.config)} | ${m.mae:,.0f} | ${m.rmse:,.0f} | "
            f"{m.r2:.4f} | {m.mape:.2%} | ${row.cv_mean:,.0f} ± {row.cv_std:,.0f} |"
        )
    lines += [
        "",
        "## Classification: at or above the median sale price",
        "",
        "The threshold is the median sale price of the training rows ($165,000 on",
        "the notebook split).",
        "",
        "| Model | alpha | Test accuracy | Precision | Recall | F1 | Test ROC-AUC "
        "| 5-fold CV ROC-AUC |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for row in results["classification"]:
        m = row.test
        assert isinstance(m, ClassificationMetrics)
        auc = "n/a" if m.roc_auc is None else f"{m.roc_auc:.4f}"
        lines.append(
            f"| {row.label} | {alpha_note(row.config)} | {m.accuracy:.2%} | {m.precision:.2%} | "
            f"{m.recall:.2%} | {m.f1:.2%} | {auc} | {row.cv_mean:.4f} ± {row.cv_std:.4f} |"
        )
    lines += [
        "",
        "## Reading the numbers",
        "",
        "- `alpha` is the regularisation strength; for classification `C = 1 / alpha`.",
        "  Defaults were chosen by 5-fold cross-validation on the training split only",
        "  (see [Design decisions](DECISIONS.md)).",
        "- On a single split, small differences are noise: the CV standard deviations",
        "  show how much a score moves between folds.",
        "- Engineered features (total area, ages, bathrooms, porch area) help gradient",
        "  boosting. For the linear models they are almost exact linear combinations",
        "  of existing columns, so they change little.",
        "",
        "## Environment",
        "",
        f"Generated on {date.today().isoformat()} with amesml {__version__}, Python "
        f"{platform.python_version()}, scikit-learn {sklearn.__version__}, pandas "
        f"{pd.__version__}, NumPy {np.__version__}.",
        "",
        "Regenerate with `make benchmark` or `python scripts/benchmark.py`.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--data", type=Path, default=None, help="Training CSV (default: data/train.csv)."
    )
    parser.add_argument("--out", type=Path, default=Path("docs/benchmarks.md"))
    args = parser.parse_args()

    warnings.filterwarnings("ignore", message="Found unknown categories")
    frame = load_ames(args.data)
    # newline="\n" keeps the file identical when regenerated on Windows.
    with args.out.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(render(run(frame)))
    print(f"Wrote {args.out}")


if __name__ == "__main__":
    main()
